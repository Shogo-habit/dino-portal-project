function generateMarkdown(dino) {
  const frontmatter = [
    '---',
    `id: "${dino.id}"`,
    `name: "${dino.name}"`,
    `kana: "${dino.kana}"`,
    'aliases:',
    ...dino.aliases.map(a => `  - "${a}"`),
    `scientificName: "${dino.scientificName}"`,
    `era: "${dino.era}"`,
    `region: "${dino.region}"`,
    `diet: "${dino.diet}"`,
    `length: "${dino.length}"`,
    `weight: "${dino.weight}"`,
    `image: "${dino.image}"`,
    `group: "${dino.group}"`,
    `description: "${dino.description}"`,
    'bioTraits:',
    ...dino.bioTraits.flatMap(b => [
      '  - trait: "' + b.trait + '"',
      '    value: "' + b.value + '"',
      '    detail: "' + b.detail + '"'
    ]),
    'cyberMetadata:',
    `  bottomGap: ${dino.cyberMetadata.bottomGap}`,
    `  realHeight: ${dino.cyberMetadata.realHeight}`,
    `  realLength: ${dino.cyberMetadata.realLength}`,
    `  contentHeightPx: ${dino.cyberMetadata.contentHeightPx}`,
    `  sourceRes: ${dino.cyberMetadata.sourceRes}`,
    `  dinoLeft: "${dino.cyberMetadata.dinoLeft}"`,
    `  refRight: "${dino.cyberMetadata.refRight}"`,
    `  zoom: ${dino.cyberMetadata.zoom}`,
    '---'
  ].join('\n');

  const bodySections = dino.sections.map(s => {
    return `### ${s.title}\n\n` + s.paragraphs.join('\n\n');
  }).join('\n\n');

  return `${frontmatter}\n\n${bodySections}\n`;
}

// 実行
const outDir = path.join(__dirname, '..', 'src', 'content', 'dinosaurs');
for (const dino of dinos) {
  const md = generateMarkdown(dino);
  const filePath = path.join(outDir, `${dino.id}.md`);
  fs.writeFileSync(filePath, md, 'utf-8');
  console.log(`Generated: ${filePath}`);
}

