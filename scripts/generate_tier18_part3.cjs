// Helper to escape special characters for regex
function escapeRegExp(string) {
  return string.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

for (const dino of part3Data) {
  const filePath = path.join("src/content/dinosaurs", `${dino.id}.md`);
  if (!fs.existsSync(filePath)) {
    console.error(`File not found: ${filePath}`);
    continue;
  }

  const fileContent = fs.readFileSync(filePath, "utf8");
  const match = fileContent.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) {
    console.error(`Invalid frontmatter in ${dino.id}`);
    continue;
  }

  // Construct new Markdown
  const newFrontmatter = `---
id: "${dino.id}"
name: "${dino.name}"
kana: "${dino.kana}"
scientificName: "${dino.scientificName}"
era: "${dino.era}"
region: "${dino.region}"
diet: "${dino.diet}"
length: "${dino.length}"
weight: "${dino.weight}"
image: "images/${dino.id}.webp"
group: "${dino.group}"
description: "${dino.description}"
bioTraits:
  - trait: "${dino.bioTraits[0].trait}"
    value: "${dino.bioTraits[0].value}"
    detail: "${dino.bioTraits[0].detail}"
  - trait: "${dino.bioTraits[1].trait}"
    value: "${dino.bioTraits[1].value}"
    detail: "${dino.bioTraits[1].detail}"
cyberMetadata:
  bottomGap: ${dino.cyberMetadata.bottomGap}
  realHeight: ${Number.isInteger(dino.cyberMetadata.realHeight) ? dino.cyberMetadata.realHeight.toFixed(1) : dino.cyberMetadata.realHeight}
  realLength: ${dino.cyberMetadata.realLength}
  contentHeightPx: ${dino.cyberMetadata.contentHeightPx}
  sourceRes: ${dino.cyberMetadata.sourceRes}
  dinoLeft: "${dino.cyberMetadata.dinoLeft}"
  refRight: "${dino.cyberMetadata.refRight}"
  zoom: ${dino.cyberMetadata.zoom}
---`;

  const newBody = dino.sections.map(s => `### ${s.title}\n\n${s.content}`).join("\n\n");

  const fullOutput = `${newFrontmatter}\n\n${newBody}\n`;

  fs.writeFileSync(filePath, fullOutput, "utf8");
  console.log(`Generated: ${dino.id}`);
}
