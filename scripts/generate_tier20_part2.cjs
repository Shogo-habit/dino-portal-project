すなわち、発達した角は成体のオスにのみ見られる特徴であり、繁殖期におけるメスを巡るオス同士の激しい頭突き合い（ヘッドバッティング）や角を絡め合う儀礼的闘争（ラトリング）、さらには遠距離からの視覚的なディスプレイ（性選択）に用いられていた。頭蓋骨の天井は角から伝わる強烈な打撃衝撃に耐えられるよう極めて分厚くドーム状に強化されており、強大な首の筋肉がその衝撃を全身へと逃がすショックアブソーバーの構造を完成させていた。

顎には、植物をすり潰すのに適した木の葉状（メロンの種状）の歯が密に並び、低木層の植物を効率よく咀嚼していた。

