この環境において、リオハサウルスは群れを形成して移動する支配的なメガ・ハービボアとして君臨していた。成体になれば体重が数トンに達するため、同地域に生息していた巨大偽鰐類ファスファトスクス（*Fasolasuchus*、全長8〜10メートルに達する三畳紀最大の肉食偽鰐類）であっても、健康な大人のリオハサウルスを単独で仕留めることは極めて困難であった。群れによる防御と、太い前肢の親指の爪による強烈な打撃は、捕食者に対する確固たる抑止力として機能していた。

系統分類学において、リオハサウルスはリオハサウルス科（Riojasauridae）の模式属として位置づけられる。かつては後の超巨大竜脚類の直接の先祖と考えられたこともあったが、詳細な系統解析により、真竜脚類とは独立して「初期竜脚形類の中で独自に完全四足歩行と10m級の巨大化を成し遂げた平行進化の枝」であることが明らかとなった。

