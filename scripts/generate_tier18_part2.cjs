function generateMarkdown(item) {
  let fm = `---\n`;
  fm += `id: "${item.id}"\n`;
  fm += `name: "${item.name}"\n`;
  fm += `kana: "${item.kana}"\n`;
  fm += `scientificName: "${item.scientificName}"\n`;
  fm += `era: "${item.era}"\n`;
  fm += `region: "${item.region}"\n`;
  fm += `diet: "${item.diet}"\n`;
  fm += `length: "${item.length}"\n`;
  fm += `weight: "${item.weight}"\n`;
  fm += `image: "images/${item.id}.webp"\n`;
  fm += `group: "${item.group}"\n`;
  fm += `description: "${item.description}"\n`;
  fm += `bioTraits:\n`;
  for (const trait of item.bioTraits) {
    fm += `  - trait: "${trait.trait}"\n`;
    fm += `    value: "${trait.value}"\n`;
    fm += `    detail: "${trait.detail}"\n`;
  }
  fm += `cyberMetadata:\n`;
  fm += `  bottomGap: ${item.cyberMetadata.bottomGap}\n`;
  const formatNum = (n) => typeof n === "number" && Number.isInteger(n) ? `${n}.0` : `${n}`;
  fm += `  realHeight: ${formatNum(item.cyberMetadata.realHeight)}\n`;
  fm += `  realLength: ${formatNum(item.cyberMetadata.realLength)}\n`;
  fm += `  contentHeightPx: ${item.cyberMetadata.contentHeightPx}\n`;
  fm += `  sourceRes: ${item.cyberMetadata.sourceRes}\n`;
  if (item.cyberMetadata.dinoLeft) {
    fm += `  dinoLeft: "${item.cyberMetadata.dinoLeft}"\n`;
  }
  if (item.cyberMetadata.refRight) {
    fm += `  refRight: "${item.cyberMetadata.refRight}"\n`;
  }
  fm += `  zoom: ${item.cyberMetadata.zoom}\n`;
  fm += `---\n\n`;

  let body = "";
  for (const sec of item.sections) {
    body += `### ${sec.title}\n\n${sec.content}\n\n`;
  }

  return fm + body.trim() + "\n";
}

